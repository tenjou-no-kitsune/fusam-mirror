export const supportedLanguages = Object.freeze(Object.keys(translations))
const languageStorageKey = "fusam-language"

const requiredKeys = Object.keys(EN)
for (const language of supportedLanguages) {
	const keys = Object.keys(translations[language])
	if (keys.length !== requiredKeys.length || requiredKeys.some((key) => !(key in translations[language]))) {
		throw new Error(`Incomplete FUSAM translation: ${language}`)
	}
}

export function getLanguage() {
	const preference = getLanguagePreference()
	if (preference !== "AUTO") return preference
	for (const language of getUserLanguages()) {
		const supported = mapLocale(language)
		if (supported) return supported
	}
	return "EN"
}

export function getLanguagePreference() {
	const language = localStorage.getItem(languageStorageKey)?.toUpperCase() ?? "AUTO"
	return supportedLanguages.includes(language) ? language : "AUTO"
}

/** @param {string} language */
export function setLanguagePreference(language) {
	const value = language.toUpperCase()
	if (value !== "AUTO" && !supportedLanguages.includes(value))
		throw new RangeError(`Unsupported language: ${language}`)
	if (value === "AUTO") localStorage.removeItem(languageStorageKey)
	else localStorage.setItem(languageStorageKey, value)
}

export function getUserLanguages() {
	const languages =
		Array.isArray(navigator.languages) && navigator.languages.length
			? navigator.languages
			: [navigator.language || "en"]
	return [...new Set(languages.flatMap((language) => [language, language.split("-")[0]]))]
}

/** @param {string} locale */
function mapLocale(locale) {
	const normalized = locale.replace("_", "-").toLowerCase()
	if (normalized === "tw") return "TW"
	if (normalized === "cn") return "CN"
	if (normalized === "ua" || normalized === "uk" || normalized.startsWith("uk-")) return "UA"
	if (normalized === "zh" || normalized.startsWith("zh-hans") || /zh-(cn|sg)\b/.test(normalized)) return "CN"
	if (normalized.startsWith("zh-hant") || /zh-(tw|hk|mo)\b/.test(normalized)) return "TW"
	const code = normalized.split("-")[0].toUpperCase()
	return supportedLanguages.includes(code) ? code : undefined
}

export function getPreferredLanguageKeys() {
	const preference = getLanguagePreference()
	if (preference !== "AUTO") return [preference, preference.toLowerCase(), "EN", "en"]
	const keys = getUserLanguages().flatMap((locale) => {
		const mapped = mapLocale(locale)
		return mapped ? [locale, locale.toLowerCase(), mapped, mapped.toLowerCase()] : [locale, locale.toLowerCase()]
	})
	return [...new Set([...keys, "EN", "en"])]
}

/** @param {keyof typeof EN} key */
export function t(key) {
	return translations[getLanguage()][key] ?? EN[key]
}
